#!/usr/bin/env python3
r"""Prepare evaluation dataset from QA JSON files.

This module converts raw QA pairs (generated by data/generate-qa-pairs.sh)
into a structured EvalDataset format ready for evaluation.

QA files are named: {source-file}-qa-{chunk_num}.json
Where:
- source-file: Name of the original transcript file (without extension)
- chunk_num: 0-indexed chunk number based on LINES_PER_CHUNK and CHUNK_STEP

This script:
1. Scans QA JSON files in a directory
2. Extracts source file and chunk number from filenames
3. Computes deterministic chunk_ids matching the indexer format
4. Outputs a single EvalDataset JSON file

Usage:
    python -m evals.datasets.prepare \
        --qa-dir data/qa/@JasonLiu/video-transcripts/medium-en/qwen2.5-7b-instruct-mlx \
        --output data/eval/@JasonLiu/video-transcripts/medium-en/qwen2.5-7b-instruct-mlx/dataset.json \
        --namespace default
"""

from __future__ import annotations

import argparse
import json
import logging
import re
import sys
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(message)s")
logger = logging.getLogger(__name__)

# Constants matching data/generate-qa-pairs.sh
DEFAULT_LINES_PER_CHUNK = 100
DEFAULT_CHUNK_STEP = 50


@dataclass
class QAFile:
    """Parsed QA file information."""

    filepath: Path
    source_file: str
    chunk_num: int
    question: str
    answer: str


def parse_qa_filename(filepath: Path) -> tuple[str, int] | None:
    """Parse QA filename to extract source file and chunk number.

    Expected format: {source-file}-qa-{chunk_num}.json

    Args:
        filepath: Path to QA JSON file

    Returns:
        Tuple of (source_file, chunk_num) or None if parsing fails
    """
    filename = filepath.stem  # Remove .json extension

    # Match pattern: anything-qa-{number}
    match = re.match(r"^(.+)-qa-(\d+)$", filename)
    if not match:
        logger.warning(f"Could not parse filename: {filename}")
        return None

    source_file = match.group(1)
    chunk_num = int(match.group(2))

    return source_file, chunk_num


def load_qa_file(filepath: Path) -> QAFile | None:
    """Load and parse a QA JSON file.

    Args:
        filepath: Path to QA JSON file

    Returns:
        QAFile with parsed data or None if parsing fails
    """
    parsed = parse_qa_filename(filepath)
    if parsed is None:
        return None

    source_file, chunk_num = parsed

    try:
        with filepath.open("r", encoding="utf-8") as f:
            data = json.load(f)
    except (json.JSONDecodeError, OSError) as e:
        logger.warning(f"Could not load {filepath}: {e}")
        return None

    question = data["question"] if "question" in data else ""
    answer = data["answer"] if "answer" in data else ""

    if not question:
        logger.warning(f"Empty question in {filepath}")
        return None

    return QAFile(
        filepath=filepath,
        source_file=source_file,
        chunk_num=chunk_num,
        question=question,
        answer=answer,
    )


def generate_doc_id(source_file: str) -> str:
    """Generate a document ID from source file name.

    Converts source file name to a URL-safe identifier.

    Args:
        source_file: Original source file name

    Returns:
        Document ID suitable for use in chunk IDs
    """
    # Remove special characters, convert spaces to underscores
    doc_id = re.sub(r"[^\w\s-]", "", source_file)
    doc_id = re.sub(r"\s+", "_", doc_id)
    return doc_id.lower()


def compute_chunk_id(namespace: str, doc_id: str, chunk_index: int) -> str:
    """Compute deterministic chunk ID matching the indexer format.

    Args:
        namespace: Document namespace
        doc_id: Document ID
        chunk_index: Chunk index (0-based)

    Returns:
        Chunk ID in format: {doc_id}-chunk-{chunk_index}
    """
    # Match format in src/pipelines/indexing_pipeline.py
    return f"{doc_id}-chunk-{chunk_index}"


def compute_line_range(
    chunk_num: int,
    lines_per_chunk: int,
    chunk_step: int,
) -> tuple[int, int]:
    """Compute line range for a chunk number.

    Args:
        chunk_num: 0-indexed chunk number
        lines_per_chunk: Lines per chunk
        chunk_step: Step between chunk starts

    Returns:
        Tuple of (line_start, line_end) where lines are 1-indexed
    """
    # Chunk N starts at line (N * chunk_step + 1)
    line_start = chunk_num * chunk_step + 1
    line_end = line_start + lines_per_chunk - 1
    return line_start, line_end


def create_eval_sample(
    qa: QAFile,
    namespace: str,
    lines_per_chunk: int,
    chunk_step: int,
) -> dict:
    """Create an EvalSample dictionary from a QA file.

    Args:
        qa: Parsed QA file
        namespace: Document namespace
        lines_per_chunk: Lines per chunk
        chunk_step: Step between chunks

    Returns:
        Dictionary matching EvalSample format
    """
    doc_id = generate_doc_id(qa.source_file)
    chunk_id = compute_chunk_id(namespace, doc_id, qa.chunk_num)
    line_start, line_end = compute_line_range(qa.chunk_num, lines_per_chunk, chunk_step)

    return {
        "sample_id": f"{doc_id}:qa:{qa.chunk_num}",
        "question": qa.question,
        "answer": qa.answer,
        "source_file": f"{qa.source_file}.txt",
        "chunk_num": qa.chunk_num,
        "line_start": line_start,
        "line_end": line_end,
        "chunk_id": chunk_id,
        "relevant_chunk_ids": [chunk_id],
    }


def prepare_dataset(
    qa_dir: Path,
    namespace: str,
    lines_per_chunk: int,
    chunk_step: int,
) -> dict:
    """Prepare an EvalDataset from a directory of QA files.

    Args:
        qa_dir: Directory containing QA JSON files
        namespace: Document namespace
        lines_per_chunk: Lines per chunk
        chunk_step: Step between chunks

    Returns:
        Dictionary matching EvalDataset format
    """
    logger.info(f"Scanning QA files in: {qa_dir}")

    # Find all JSON files
    qa_files = list(qa_dir.glob("*.json"))
    logger.info(f"Found {len(qa_files)} JSON files")

    # Parse all QA files
    samples = []
    source_files: set[str] = set()

    for filepath in sorted(qa_files):
        qa = load_qa_file(filepath)
        if qa is None:
            continue

        sample = create_eval_sample(qa, namespace, lines_per_chunk, chunk_step)
        samples.append(sample)
        source_files.add(qa.source_file)

    logger.info(f"Parsed {len(samples)} QA pairs from {len(source_files)} source files")

    # Generate dataset name from path
    dataset_name = str(qa_dir).replace("data/qa/", "")

    return {
        "name": dataset_name,
        "version": "1.0.0",
        "created_at": datetime.now(UTC).isoformat().replace("+00:00", "Z"),
        "chunk_config": {
            "lines_per_chunk": lines_per_chunk,
            "chunk_step": chunk_step,
        },
        "samples": samples,
        "metadata": {
            "total_samples": len(samples),
            "total_source_files": len(source_files),
            "qa_source_dir": str(qa_dir),
            "namespace": namespace,
        },
    }


def main() -> int:
    """Main entry point."""
    parser = argparse.ArgumentParser(description="Prepare evaluation dataset from QA JSON files")
    parser.add_argument(
        "--qa-dir",
        type=Path,
        required=True,
        help="Directory containing QA JSON files",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Output path for EvalDataset JSON",
    )
    parser.add_argument(
        "--namespace",
        type=str,
        default="default",
        help="Document namespace (default: default)",
    )
    parser.add_argument(
        "--lines-per-chunk",
        type=int,
        default=DEFAULT_LINES_PER_CHUNK,
        help=f"Lines per chunk (default: {DEFAULT_LINES_PER_CHUNK})",
    )
    parser.add_argument(
        "--chunk-step",
        type=int,
        default=DEFAULT_CHUNK_STEP,
        help=f"Chunk step (default: {DEFAULT_CHUNK_STEP})",
    )

    args = parser.parse_args()

    if not args.qa_dir.exists():
        logger.error(f"QA directory does not exist: {args.qa_dir}")
        return 1

    # Prepare dataset
    dataset = prepare_dataset(
        args.qa_dir,
        namespace=args.namespace,
        lines_per_chunk=args.lines_per_chunk,
        chunk_step=args.chunk_step,
    )

    if not dataset["samples"]:
        logger.error("No valid QA samples found")
        return 1

    # Write output
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as f:
        json.dump(dataset, f, indent=2, ensure_ascii=False)

    logger.info(f"Wrote dataset to: {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
